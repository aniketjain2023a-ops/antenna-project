"""Deterministic SYNTHETIC demonstration dataset.

IMPORTANT - SCIENTIFIC HONESTY
------------------------------
This module does NOT solve Maxwell's equations and is NOT an electromagnetic
simulation. It is a smooth, *physics-inspired* analytical surrogate chosen so
that regression and optimization can be demonstrated with a realistic shape:
a narrow resonance valley in S11, a coupled gain response and a genuine
trade-off between matching and gain. All numbers below are assumptions made
for demonstration and are documented here and in ``data/README.md``.

Model (all assumptions)
-----------------------
Inputs
    L  - effective patch/metasurface length  [mm], sampled in [8.0, 12.5]
    G  - metasurface gap                     [mm], sampled in [0.2, 2.0]

1. Gap loading lengthens the effective resonator (fringing / capacitive
   loading assumption)::

       dL(G) = 0.4 / (G + 0.4)                                   [mm]

2. Half-wavelength resonance with an assumed effective permittivity
   ``EPS_EFF = 2.0`` (standard patch-antenna approximation, e.g. Balanis)::

       f_r(L, G) = c / (2 * (L + 2 dL) * sqrt(EPS_EFF))

3. Single-resonance reflection model at the design frequency
   ``F0 = 10 GHz`` with an assumed loaded quality factor ``Q = 5``::

       delta      = (f_r - F0) / F0
       Gamma_min  = 0.05 + 0.25 * (1 - exp(-((G - 0.8) / 0.6)^2))
       |Gamma|^2  = 1 - (1 - Gamma_min^2) / (1 + (2 Q delta)^2)
       S11_dB     = 10 log10(|Gamma|^2)

   so the best match occurs on the resonance curve near G = 0.8 mm.

4. Realized gain = assumed directivity + mismatch loss - fixed loss::

       D_dBi   = 6.5 + 0.35 (L - 8) + 1.2 exp(-((G - 1.3) / 0.45)^2)
       Gain    = D_dBi + 10 log10(1 - |Gamma|^2) - 0.3

   The metasurface enhancement term peaks at G = 1.3 mm, i.e. at a different
   gap than the best match - this creates the gain/S11 trade-off.

5. Measurement-like noise (Gaussian, fixed seed): sigma = 0.6 dB on S11 and
   0.15 dB on gain. S11 is clipped to <= -0.05 dB because a passive antenna
   cannot reflect more power than is incident (|Gamma| <= 1).

Sampling uses a seeded Latin hypercube so that the dataset is reproducible
bit-for-bit for a given seed and sample count.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
from scipy.stats import qmc

from utils.compat import seed_kwargs

C0 = 299_792_458.0          # speed of light in vacuum [m/s]
F0_GHZ = 10.0               # assumed design frequency [GHz]
EPS_EFF = 2.0               # assumed effective permittivity [-]
Q_LOADED = 5.0              # assumed loaded quality factor [-]
L_RANGE_MM = (8.0, 12.5)
G_RANGE_MM = (0.2, 2.0)
S11_NOISE_DB = 0.6
GAIN_NOISE_DB = 0.15
FIXED_LOSS_DB = 0.3

FEATURES = ["L_mm", "G_mm"]
TARGETS = ["S11_dB", "Gain_dBi"]

PROVENANCE = (
    "SYNTHETIC. Generated by datasets/synthetic.py (MetaOpt-AI) from a documented, "
    "physics-inspired analytical formula (half-wave resonance with assumed eps_eff=2.0, "
    "F0=10 GHz, Q=5, gap-dependent matching and metasurface gain term) plus seeded "
    "Gaussian noise. NOT an EM simulation, NOT a measurement."
)


def gap_extension_mm(g_mm):
    return 0.4 / (np.asarray(g_mm, dtype=float) + 0.4)


def resonant_frequency_ghz(l_mm, g_mm):
    l_eff_m = (np.asarray(l_mm, dtype=float) + 2.0 * gap_extension_mm(g_mm)) * 1e-3
    return C0 / (2.0 * l_eff_m * np.sqrt(EPS_EFF)) / 1e9


def reflection_power(l_mm, g_mm):
    """Return |Gamma|^2 (noise-free)."""
    g = np.asarray(g_mm, dtype=float)
    delta = (resonant_frequency_ghz(l_mm, g) - F0_GHZ) / F0_GHZ
    gamma_min = 0.05 + 0.25 * (1.0 - np.exp(-((g - 0.8) / 0.6) ** 2))
    return 1.0 - (1.0 - gamma_min**2) / (1.0 + (2.0 * Q_LOADED * delta) ** 2)


def s11_db_clean(l_mm, g_mm):
    return 10.0 * np.log10(reflection_power(l_mm, g_mm))


def gain_dbi_clean(l_mm, g_mm):
    l = np.asarray(l_mm, dtype=float)
    g = np.asarray(g_mm, dtype=float)
    directivity = 6.5 + 0.35 * (l - 8.0) + 1.2 * np.exp(-((g - 1.3) / 0.45) ** 2)
    mismatch = 10.0 * np.log10(1.0 - reflection_power(l, g))
    return directivity + mismatch - FIXED_LOSS_DB


def generate_synthetic_dataset(n_samples: int = 500, seed: int = 42) -> pd.DataFrame:
    """Generate the deterministic synthetic dataset (Latin hypercube + noise)."""
    if n_samples < 10:
        raise ValueError("n_samples must be at least 10.")
    sampler = qmc.LatinHypercube(d=2, **seed_kwargs(qmc.LatinHypercube, seed))
    unit = sampler.random(n_samples)
    lows = [L_RANGE_MM[0], G_RANGE_MM[0]]
    highs = [L_RANGE_MM[1], G_RANGE_MM[1]]
    pts = qmc.scale(unit, lows, highs)
    l_mm, g_mm = pts[:, 0], pts[:, 1]

    rng = np.random.default_rng(seed + 1)
    s11 = s11_db_clean(l_mm, g_mm) + rng.normal(0.0, S11_NOISE_DB, n_samples)
    s11 = np.minimum(s11, -0.05)
    gain = gain_dbi_clean(l_mm, g_mm) + rng.normal(0.0, GAIN_NOISE_DB, n_samples)

    return pd.DataFrame(
        {
            "sample_id": np.arange(1, n_samples + 1),
            "L_mm": np.round(l_mm, 4),
            "G_mm": np.round(g_mm, 4),
            "S11_dB": np.round(s11, 4),
            "Gain_dBi": np.round(gain, 4),
            "data_label": "SYNTHETIC",
        }
    )
